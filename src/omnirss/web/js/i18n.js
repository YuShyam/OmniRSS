/**
 * Translate a key into the active language with optional parameter interpolation.
 *
 * @param {string} key - The dictionary key (e.g. "feed_props.title")
 * @param {Object|string} [paramsOrFallback={}] - Interpolation dictionary or fallback string
 * @param {string} [fallback=""] - Fallback string if params was an object
 * @returns {string} Translated and formatted string
 */
export function t(key, paramsOrFallback = {}, fallback = "") {
  if (!key || key === "null" || key === "undefined") return "";
  const currentLang = store.get("lang") || "zh-TW";
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS["zh-TW"] || {};

  let params = {};
  let fallbackStr = "";

  if (typeof paramsOrFallback === "string") {
    fallbackStr = paramsOrFallback;
  } else if (typeof paramsOrFallback === "object" && paramsOrFallback !== null) {
    params = paramsOrFallback;
    fallbackStr = fallback;
  }

  let str = dict[key];
  if (str === undefined || str === null || str === "null" || str === "undefined") {
    str = TRANSLATIONS["zh-TW"]?.[key] ?? (fallbackStr || key);
  }

  str = String(str);
  for (const [k, v] of Object.entries(params)) {
    const safeVal = (v === null || v === undefined || v === "null" || v === "undefined") ? "" : String(v);
    str = str.replace(new RegExp(`\\{${k}\\}`, "g"), () => safeVal);
  }
  return str;
}

/**
 * Update all static elements in the DOM with data-i18n attributes.
 */
export function updateDomTranslations() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) {
      const val = t(key);
      if (val && val !== "null" && val !== "undefined") {
        el.textContent = val;
      }
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) {
      const val = t(key);
      if (val && val !== "null" && val !== "undefined") {
        el.setAttribute("placeholder", val);
      }
    }
  });

  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key) {
      const val = t(key);
      if (val && val !== "null" && val !== "undefined") {
        el.setAttribute("title", val);
      }
    }
  });

  // 全域清理所有殘留 "null" 或 "undefined" 字串之輸入框與佔位符
  document.querySelectorAll("input, textarea").forEach((el) => {
    if (el.value === "null" || el.value === "undefined") {
      el.value = "";
    }
    if (el.getAttribute("placeholder") === "null" || el.getAttribute("placeholder") === "undefined") {
      el.removeAttribute("placeholder");
    }
  });
}
